/// Extract triangles for a cube configuration using the canonical MC_TABLE.
///
/// Returns a list of triangles as `[edge0, edge1, edge2]` index triples.
/// Edge indices index into the caller's 12-element edge-vertex array.
fn mc_triangulate(cube_idx: u8) -> Vec<[usize; 3]> {
    let row = &MC_TABLE[cube_idx as usize];
    let mut tris = Vec::with_capacity(5);
    let mut i = 0;
    while i + 2 < 16 {
        let a = row[i];
        let b = row[i + 1];
        let c = row[i + 2];
        if a < 0 {
            break;
        }
        tris.push([a as usize, b as usize, c as usize]);
        i += 3;
    }
    tris
}
