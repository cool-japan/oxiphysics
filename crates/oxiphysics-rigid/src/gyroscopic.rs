/// Multiply two unit quaternions `p * q` (scalar-last: \[x, y, z, w\]).
#[cfg(test)]
#[inline]
fn quat_mul(p: [f64; 4], q: [f64; 4]) -> [f64; 4] {
    let [px, py, pz, pw] = p;
    let [qx, qy, qz, qw] = q;
    [
        pw * qx + px * qw + py * qz - pz * qy,
        pw * qy - px * qz + py * qw + pz * qx,
        pw * qz + px * qy - py * qx + pz * qw,
        pw * qw - px * qx - py * qy - pz * qz,
    ]
}

/// Normalise a quaternion.
#[inline]
fn quat_norm(q: [f64; 4]) -> [f64; 4] {
    let mag = (q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]).sqrt();
    if mag < 1e-15 {
        return [0.0, 0.0, 0.0, 1.0];
    }
    [q[0] / mag, q[1] / mag, q[2] / mag, q[3] / mag]
}

/// Integrate orientation quaternion by angular-velocity `omega` over `dt` (first-order).
fn quat_integrate(q: [f64; 4], omega: [f64; 3], dt: f64) -> [f64; 4] {
    let half_dt = 0.5 * dt;
    let dq = [
        (omega[0] * q[3] + omega[2] * q[1] - omega[1] * q[2]) * half_dt,
        (omega[1] * q[3] - omega[2] * q[0] + omega[0] * q[2]) * half_dt,
        (omega[2] * q[3] + omega[1] * q[0] - omega[0] * q[1]) * half_dt,
        (-omega[0] * q[0] - omega[1] * q[1] - omega[2] * q[2]) * half_dt,
    ];
    quat_norm([q[0] + dq[0], q[1] + dq[1], q[2] + dq[2], q[3] + dq[3]])
}

