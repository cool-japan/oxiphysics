/// Compute the gyroscopic torque **ω × (I·ω)** acting on the spinning body.
///
/// This is the reaction torque generated by the angular momentum; it opposes
/// attempts to change the orientation of the spin axis.
pub fn gyroscopic_torque(gyro: &Gyroscope) -> [f64; 3] {
    let w = gyro.angular_velocity;
    let [ix, iy, iz] = gyro.moment_of_inertia;
    let iw = [ix * w[0], iy * w[1], iz * w[2]];
    cross(w, iw)
}

/// Compute the right-hand side of **Euler's rotation equations**:
///
/// ```text
/// Ix * α_x = τ_x − (Iz − Iy) * ω_y * ω_z
/// Iy * α_y = τ_y − (Ix − Iz) * ω_z * ω_x
/// Iz * α_z = τ_z − (Iy − Ix) * ω_x * ω_y
/// ```
///
/// Returns the angular acceleration `[α_x, α_y, α_z]`.
pub fn euler_equations_rhs(gyro: &Gyroscope, external_torque: [f64; 3]) -> [f64; 3] {
    let [ix, iy, iz] = gyro.moment_of_inertia;
    let [wx, wy, wz] = gyro.angular_velocity;
    let [tx, ty, tz] = external_torque;
    let ax = (tx - (iz - iy) * wy * wz) / ix;
    let ay = (ty - (ix - iz) * wz * wx) / iy;
    let az = (tz - (iy - ix) * wx * wy) / iz;
    [ax, ay, az]
}

/// Compute the steady-state **precession rate** (rad/s) of a symmetric top.
///
/// Formula: `Ω_p = τ / (Iz * Ω_spin)` where τ is the applied torque magnitude.
///
/// * `spin_rate` — rotor angular speed (rad/s).
/// * `iz` — axial (spin-axis) moment of inertia (kg·m²).
/// * `ix` — transverse moment of inertia (kg·m²) — not used in the simplified
///   formula but included for completeness.
/// * `torque_magnitude` — magnitude of the tilting torque (N·m).
pub fn precession_rate(spin_rate: f64, iz: f64, _ix: f64, torque_magnitude: f64) -> f64 {
    let denom = iz * spin_rate;
    if denom.abs() < 1e-15 {
        0.0
    } else {
        torque_magnitude / denom
    }
}

/// Compute the **nutation (body-cone) frequency** for a torque-free symmetric top.
///
/// `ω_nut = ((Iz − Ix) / Ix) * Ω_spin`
///
/// * `iz` — axial moment of inertia (kg·m²).
/// * `ix` — transverse moment of inertia (kg·m²).
/// * `spin_rate` — spin rate about the symmetry axis (rad/s).
pub fn nutation_frequency(iz: f64, ix: f64, spin_rate: f64) -> f64 {
    if ix.abs() < 1e-15 {
        return 0.0;
    }
    ((iz - ix) / ix) * spin_rate
}

/// Compute the **gyrocompass alignment torque** (N·m) produced by Earth's rotation.
///
/// A gyrocompass aligns its spin axis to true north due to the interaction of
/// Earth's angular velocity with the gyroscope's angular momentum.
///
/// `τ_align = Iz * Ω_spin * Ω_earth * cos(lat)`
///
/// * `latitude_rad` — geographic latitude in radians.
/// * `earth_rate` — Earth's rotation rate (rad/s, ≈ 7.27 × 10⁻⁵).
pub fn gyrocompass_effect(gyro: &Gyroscope, latitude_rad: f64, earth_rate: f64) -> f64 {
    let iz = gyro.moment_of_inertia[2];
    iz * gyro.spin_rate * earth_rate * latitude_rad.cos()
}

/// Estimate the **stabilisation time** constant (s) for a damped gyroscope.
///
/// `T = Iz * Ω_spin / damping`
///
/// * `damping` — viscous damping coefficient (N·m·s/rad).
pub fn stabilization_time(gyro: &Gyroscope, damping: f64) -> f64 {
    let iz = gyro.moment_of_inertia[2];
    if damping.abs() < 1e-15 {
        f64::INFINITY
    } else {
        (iz * gyro.spin_rate.abs()) / damping
    }
}

/// Check whether a spin-stabilised satellite is dynamically stable.
///
/// Major-axis spin stability requires `Iz > Ix` (prolate spinner).
///
/// * `iz` — axial moment of inertia (kg·m²).
/// * `ix` — transverse moment of inertia (kg·m²).
/// * `spin` — spin rate (rad/s) — must be non-zero.
pub fn spin_stabilized_satellite(iz: f64, ix: f64, spin: f64) -> bool {
    spin.abs() > 1e-15 && iz > ix
}

