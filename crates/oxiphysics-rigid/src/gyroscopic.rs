/// A rigid rotor described by its spin axis, spin rate, inertia tensor diagonal,
/// body-frame angular velocity, and orientation quaternion.
#[derive(Debug, Clone)]
pub struct Gyroscope {
    /// Unit vector along the rotor's symmetry (spin) axis in the body frame.
    pub spin_axis: [f64; 3],
    /// Spin rate of the rotor about its symmetry axis (rad/s).
    pub spin_rate: f64,
    /// Diagonal moments of inertia `[Ix, Iy, Iz]` (kg·m²).
    pub moment_of_inertia: [f64; 3],
    /// Body-frame angular velocity vector (rad/s).
    pub angular_velocity: [f64; 3],
    /// Orientation quaternion (scalar-last: \[x, y, z, w\]).
    pub orientation: [f64; 4],
}

impl Gyroscope {
    /// Create a new `Gyroscope` with default identity orientation.
    ///
    /// * `spin_axis` — unit vector for rotor symmetry axis (body frame).
    /// * `spin_rate` — initial spin rate (rad/s).
    /// * `moment_of_inertia` — `[Ix, Iy, Iz]` (kg·m²).
    pub fn new(spin_axis: [f64; 3], spin_rate: f64, moment_of_inertia: [f64; 3]) -> Self {
        let n = norm(spin_axis);
        let axis = if n > 1e-15 {
            scale(spin_axis, 1.0 / n)
        } else {
            [0.0, 0.0, 1.0]
        };
        Self {
            spin_axis: axis,
            spin_rate,
            moment_of_inertia,
            angular_velocity: scale(axis, spin_rate),
            orientation: [0.0, 0.0, 0.0, 1.0],
        }
    }
}

