/// Compute the angular-velocity derivative `dω/dt` from Euler's equations.
fn omega_dot(gyro: &Gyroscope, external_torque: [f64; 3]) -> [f64; 3] {
    euler_equations_rhs(gyro, external_torque)
}

/// Step the gyroscope forward by `dt` seconds under `external_torque` using RK4.
///
/// Both angular velocity and orientation quaternion are updated.
pub fn step_gyroscope(gyro: &mut Gyroscope, external_torque: [f64; 3], dt: f64) {
    let w0 = gyro.angular_velocity;

    // RK4 on angular velocity
    let k1 = omega_dot(gyro, external_torque);

    let mut tmp = gyro.clone();
    tmp.angular_velocity = add3(w0, scale(k1, dt * 0.5));
    let k2 = omega_dot(&tmp, external_torque);

    tmp.angular_velocity = add3(w0, scale(k2, dt * 0.5));
    let k3 = omega_dot(&tmp, external_torque);

    tmp.angular_velocity = add3(w0, scale(k3, dt));
    let k4 = omega_dot(&tmp, external_torque);

    let w_new = [
        w0[0] + dt / 6.0 * (k1[0] + 2.0 * k2[0] + 2.0 * k3[0] + k4[0]),
        w0[1] + dt / 6.0 * (k1[1] + 2.0 * k2[1] + 2.0 * k3[1] + k4[1]),
        w0[2] + dt / 6.0 * (k1[2] + 2.0 * k2[2] + 2.0 * k3[2] + k4[2]),
    ];

    gyro.orientation = quat_integrate(gyro.orientation, w0, dt);
    gyro.angular_velocity = w_new;

    // Update spin_rate as the component along the spin axis
    gyro.spin_rate = dot(gyro.angular_velocity, gyro.spin_axis);
}

/// Advance the gyroscope by `dt` seconds with **no external torque** applied.
///
/// Equivalent to `step_gyroscope(gyro, [0.0, 0.0, 0.0], dt)`.
pub fn torque_free_motion(gyro: &mut Gyroscope, dt: f64) {
    step_gyroscope(gyro, [0.0, 0.0, 0.0], dt);
}

